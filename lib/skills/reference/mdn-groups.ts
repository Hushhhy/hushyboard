export function cssPropertyGroup(name: string): string {
  if (CSS_OVERRIDES[name]) return CSS_OVERRIDES[name];
  return CSS_GROUP_RULES.find(([rule]) => rule.test(name))?.[1] ?? 'Autres';
}

